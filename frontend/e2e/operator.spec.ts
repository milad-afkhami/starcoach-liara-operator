test('same owner can recover watch history in a fresh session and revoked session stays signed out',async({page,browser})=>{
 await login(page)
 await page.getByRole('button',{name:'باز کردن storefront'}).click()
 await page.getByRole('button',{name:'شروع پایش ۱۵ دقیقه‌ای'}).click()
 await expect(page.getByTestId('watch-panel')).toContainText('پایش این سرویس فعال است')
 const watch=(await (await page.request.get('/api/state')).json()).watches.find((w:any)=>w.state==='active')
 const second=await browser.newContext()
 const fresh=await second.newPage()
 try{
  await login(fresh)
  await fresh.getByRole('button',{name:'باز کردن storefront'}).click()
  await expect(fresh.getByTestId('watch-panel')).toContainText('پایش این سرویس فعال است')
  await fresh.getByRole('button',{name:'توقف پایش',exact:true}).click()
  await expect(fresh.getByTestId('watch-panel')).toContainText('متوقف‌شده')
  await fresh.getByRole('button',{name:'خروج',exact:true}).click()
  await expect(fresh.getByLabel('رمز مالک')).toBeVisible()
  expect((await fresh.request.get('/api/state')).status()).toBe(401)
  await login(fresh)
  await fresh.getByRole('button',{name:'باز کردن storefront'}).click()
  await expect(fresh.getByTestId('watch-panel')).toContainText('متوقف‌شده')
  const restored=await (await fresh.request.get('/api/state')).json()
  expect(restored.watches.some((w:any)=>w.id===watch.id&&w.state==='stopped')).toBe(true)
 }finally{
  // Original session remains authenticated, allowing cleanup even if the second login regression fails.
  await page.request.post('/api/watches/'+watch.id+'/stop',{headers:{Origin:'http://127.0.0.1:8661'}})
  await second.close()
 }
})

