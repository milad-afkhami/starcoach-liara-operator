import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
test.skip(process.env.LIARA_OUTCOME_FIXTURE!=='1','Requires seeded presentation cases in the deterministic fixture')
const access=JSON.parse(readFileSync(process.env.LIARA_TEST_ACCESS_FILE!,'utf8'))
async function login(page:any){await page.goto('/');await page.getByLabel('رمز مالک').fill(access.password);await page.getByRole('button',{name:'ورود',exact:true}).click();await expect(page.getByRole('heading',{name:'سرویس‌ها',exact:true})).toBeVisible()}
async function selectCase(page:any,name:string){
 const incidents=(await (await page.request.get('/api/state')).json()).incidents
 const incident=incidents.find((i:any)=>i.question==='UI CASE: '+name);expect(incident).toBeTruthy()
 const history=page.locator('.recent');if(!await history.evaluate((el:HTMLDetailsElement)=>el.open))await history.locator('summary').click()
 await history.locator(`[data-incident-id="${incident.id}"]`).click()
 await expect(history.locator(`[data-incident-id="${incident.id}"]`)).toHaveAttribute('aria-pressed','true')
 await expect(page.getByTestId('incident-panel')).toBeVisible()
 return incident
}
async function prompt(page:any,summary:string){
 await page.getByText(summary,{exact:true}).click()
 const handoff=page.getByRole('region',{name:'راهنمای آماده برای Codex'})
 await expect(handoff).toBeVisible();await handoff.getByText('دیدن متن قبل از کپی',{exact:true}).click()
 return handoff.getByRole('textbox',{name:'متن آماده برای Codex'}).inputValue()
}
test('healthy and uncertain results preserve full diagnosis and offer only optional review without guessed next steps',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));await login(page)
 const healthy=await selectCase(page,'nochange')
 expect(healthy.diagnosis.summary.length).toBeGreaterThan(300)
 await expect(page.locator('.diagnosis-brief>p')).toHaveText(healthy.diagnosis.summary)
 await expect(page.locator('.next-action')).toHaveCount(0)
 await expect(page.getByRole('region',{name:'راهنمای آماده برای Codex'})).toBeHidden()
 await page.screenshot({path:'../docs/qa-evidence/liara-r2a-healthy-desktop.png',fullPage:true})
 const text=await prompt(page,'ارسال نتیجه برای بازبینی (اختیاری)')
 expect(text).toContain('Do not modify code');expect(text).not.toContain('make the smallest appropriate fix');expect(text).toContain(healthy.diagnosis.summary);expect(text).toContain('سورس پروژه بررسی نشده است.')
 await selectCase(page,'need');await expect(page.getByRole('region',{name:'راهنمای آماده برای Codex'})).toBeHidden()
 expect(await prompt(page,'بررسی بیشتر با Codex (اختیاری)')).toContain('Do not modify code')
 await selectCase(page,'stale');await expect(page.getByRole('button',{name:'تأیید همین deploy'})).toBeDisabled()
 expect(await prompt(page,'بازبینی نتیجهٔ قبلی با Codex (اختیاری)')).toContain('not current for the incident generation')
 expect(errors).toEqual([])
})
