test('setup starts with transparent sample inputs and measured minima remain optional and editable',async({page})=>{
 await login(page);await page.getByRole('button',{name:'راهنمای راه‌اندازی سرویس تازه'}).click()
 const dialog=page.getByRole('dialog',{name:'راهنمای راه‌اندازی'})
 await expect(dialog.getByLabel('حداقل RAM (GB)')).toBeHidden();await expect(dialog).toContainText('فقط نمونه‌اند')
 let request=page.waitForRequest(r=>r.url().endsWith('/api/setup/recommendation')&&r.method()==='POST')
 await dialog.getByRole('button',{name:'دریافت راهنمای شروع',exact:true}).click();expect((await request).postDataJSON()).toEqual({workload:'web',ram_gb:.5,cpu_cores:.5,disk_gb:5})
 await expect(dialog.getByRole('heading',{name:'پیشنهاد شروع'})).toBeVisible()
 await dialog.getByText('منابع اندازه‌گیری‌شده را دارم (اختیاری)',{exact:true}).click()
 await dialog.getByLabel('حداقل RAM (GB)').fill('1');await dialog.getByLabel('حداقل CPU (هسته)').fill('1');await dialog.getByLabel('حداقل دیسک (GB)').fill('8')
 request=page.waitForRequest(r=>r.url().endsWith('/api/setup/recommendation')&&r.method()==='POST')
 await dialog.getByRole('button',{name:'دریافت راهنمای شروع',exact:true}).click();expect((await request).postDataJSON()).toEqual({workload:'web',ram_gb:1,cpu_cores:1,disk_gb:8})
 await expect(dialog).toContainText('قیمت یا پلن فرضی پیشنهاد نمی‌شود')
})
